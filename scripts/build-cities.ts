/**
 * Generate src/data/worldCities.ts: every city with at least 100,000
 * people, plus every capital, for the search field. Bundled with the app so
 * a search never leaves the phone.
 *
 *   npm run cities
 *
 * Source: GeoNames (CC BY 4.0) via the all-the-cities package. Country names
 * come from Intl (English).
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

interface Raw {
  name: string;
  country: string;
  featureCode: string;
  population: number;
  loc: { coordinates: [number, number] };
}

const require = createRequire(import.meta.url);
const all = require('all-the-cities') as Raw[];
const MIN_POPULATION = 100_000;

const cities = all
  // Districts of a city (PPLX, such as Vienna's Favoriten) and historical places are not cities.
  .filter((c) => c.featureCode !== 'PPLX' && c.featureCode !== 'PPLH')
  .filter((c) => c.population >= MIN_POPULATION || c.featureCode === 'PPLC')
  .sort((a, b) => b.population - a.population);

const regionNames = new Intl.DisplayNames(['en'], { type: 'region' });
const countries: Record<string, string> = {};
for (const c of cities) countries[c.country] ??= regionNames.of(c.country) ?? c.country;

const round = (n: number) => Math.round(n * 1e4) / 1e4;
const rows = cities.map(
  (c) =>
    `  [${JSON.stringify(c.name)}, '${c.country}', ${round(c.loc.coordinates[0])}, ${round(c.loc.coordinates[1])}, ${c.population}],`,
);

const out = `/**
 * Generated by scripts/build-cities.ts. Do not edit by hand.
 * ${cities.length} cities with at least ${MIN_POPULATION.toLocaleString('en')} people, plus every capital,
 * largest first. City data © GeoNames (CC BY 4.0).
 */

export const COUNTRIES: Record<string, string> = ${JSON.stringify(countries, null, 2)};

/** [name, country code, longitude, latitude, population] */
export const WORLD_CITIES: readonly [string, string, number, number, number][] = [
${rows.join('\n')}
];
`;

writeFileSync(join(import.meta.dirname, '../src/data/worldCities.ts'), out);
console.log(`Wrote ${cities.length} cities in ${Object.keys(countries).length} countries.`);
